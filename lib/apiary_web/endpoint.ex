defmodule ApiaryWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :apiary

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  @session_options [
    store: :cookie,
    key: "_apiary_key",
    signing_salt: "pFOPn1LM",
    same_site: "Lax"
  ]

  # The peer's address, the user agent and, behind a trusted proxy, `X-Forwarded-For` are
  # where a change came from, for the audit trail (`ApiaryWeb.Origin`).
  #
  # A websocket frame is bounded at 4 MiB: the largest legitimate event, a whole proposal
  # edit at the field caps, is about 2.7 MB form-encoded. A fragmented message has the same
  # bound, set for Bandit's `http:` in config/config.exs and for an `https:` at boot
  # (`bound_https/1`); "/live" is the only socket outside dev, so it reaches nothing else.
  # Longpoll has no such option and keeps Bandit's fixed 8 MB request-body read.
  socket "/live", Phoenix.LiveView.Socket,
    websocket: [
      connect_info: [:peer_data, :user_agent, :x_headers, session: @session_options],
      max_frame_size: 4_194_304
    ],
    longpoll: [connect_info: [:peer_data, :user_agent, :x_headers, session: @session_options]]

  # Serve at "/" the static files from "priv/static" directory: the edition's first, when
  # it is an application of its own (`ApiaryWeb.Edition.static_app/0`), so that its built
  # assets shadow the core's, then the core's, whose fonts and images an edition serves as
  # they are.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  if ApiaryWeb.Edition.static_app() != :apiary do
    plug Plug.Static,
      at: "/",
      from: ApiaryWeb.Edition.static_app(),
      gzip: not code_reloading?,
      only: ApiaryWeb.static_paths()
  end

  plug Plug.Static,
    at: "/",
    from: :apiary,
    gzip: not code_reloading?,
    only: ApiaryWeb.static_paths(),
    raise_on_missing_only: code_reloading?

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    socket "/phoenix/live_reload/socket", Phoenix.LiveReloader.Socket
    plug Phoenix.LiveReloader
    plug Phoenix.CodeReloader
    plug Phoenix.Ecto.CheckRepoStatus, otp_app: :apiary
  end

  # The content security policy and its nonce (`ApiaryWeb.ContentSecurityPolicy`), on the
  # documentation and on every answer of the router, error pages included. After the code
  # reloader, whose live-reload frame and compile error page are development tools' own.
  plug ApiaryWeb.ContentSecurityPolicy

  # The documentation, from the tree built for the instance's features: `priv/static/docs`
  # holds one per set of features, and `dir/0` names the one to read.
  plug Plug.Static,
    at: "/docs",
    from: {ApiaryWeb.DocsController, :dir, []},
    gzip: not code_reloading?

  plug Phoenix.LiveDashboard.RequestLogger,
    param_key: "request_logger",
    cookie_key: "request_logger"

  plug Plug.RequestId

  # Emits [:phoenix, :endpoint, :start | :stop]. In production the JSON request log
  # (LoggerJSON.Plug, attached in Apiary.Application) listens to the stop event; the
  # Phoenix request logger is off there, so each request produces one line.
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint]

  # A delivery to the events endpoint is signed over its raw bytes and verified
  # before it is parsed: its body is read and kept here, and the parsers skip it.
  plug ApiaryWeb.Contract.RawBody
  plug :parse_body

  plug Plug.MethodOverride
  plug Plug.Head
  plug Plug.Session, @session_options
  # A route of a feature this instance does not have is a path the router does not know.
  plug ApiaryWeb.Features.Routes

  # The edition's router (`ApiaryWeb.Edition.router/0`), called at runtime: `plug Router`
  # would initialise it while this module compiles, before an edition's router exists.
  # So its calls are not checked here either, nor the code reloader's, whose application
  # a build of the core as another project's dependency does not have while it compiles.
  @compile {:no_warn_undefined, [ApiaryWeb.Edition.router(), Phoenix.LiveReloader]}
  plug :dispatch

  @parsers Plug.Parsers.init(
             parsers: [:urlencoded, :multipart, :json],
             pass: ["*/*"],
             json_decoder: Phoenix.json_library()
           )

  defp parse_body(%Plug.Conn{assigns: %{raw_body: _}} = conn, _opts), do: conn
  defp parse_body(conn, _opts), do: Plug.Parsers.call(conn, @parsers)

  defp dispatch(conn, _opts) do
    router = ApiaryWeb.Edition.router()
    router.call(conn, router.init([]))
  end

  # The bound on a fragmented message, the one config/config.exs sets under `http:`.
  @max_fragmented_message_size 4_194_304

  @doc false
  # The endpoint's configuration with the bound on a fragmented message put into its
  # `https:` as well, unless that `https:` names a bound already. Called at boot
  # (`Apiary.Application`): config/config.exs cannot set it there, since, with the server
  # on, Phoenix starts an https listener for any `https:` that is set. An `https:` that is
  # not a list (absent, `nil` or `false`) is left as it is, so this never adds a listener.
  def bound_https(config) do
    with https when is_list(https) <- config[:https],
         {:websocket_options, websocket} when is_list(websocket) <-
           List.keyfind(https, :websocket_options, 0, {:websocket_options, []}) do
      websocket =
        Keyword.put_new(websocket, :max_fragmented_message_size, @max_fragmented_message_size)

      https = List.keystore(https, :websocket_options, 0, {:websocket_options, websocket})
      Keyword.put(config, :https, https)
    else
      _absent -> config
    end
  end
end
